from notion_client import Client

def format_notes_for_notion(notes):
    """
    Convert the markdown notes into Notion blocks for structured formatting.
    Args:
        notes (str): The structured notes generated by LLM.
    Returns:
        list: A list of Notion blocks to send to the Notion API.
    """
    if isinstance(notes, list):
        return notes

    blocks = []
    for line in notes.split("\n"):
        line_stripped = line.strip()
        if not line_stripped:
            continue

        if line_stripped.startswith("### "):  # Convert sub-subheadings
            blocks.append({
                "object": "block",
                "type": "heading_3",
                "heading_3": {
                    "rich_text": [{"type": "text", "text": {"content": line_stripped[4:]}}],
                },
            })
        elif line_stripped.startswith("## "):  # Convert subheadings
            blocks.append({
                "object": "block",
                "type": "heading_2",
                "heading_2": {
                    "rich_text": [{"type": "text", "text": {"content": line_stripped[3:]}}],
                },
            })
        elif line_stripped.startswith("# "):  # Convert headings
            blocks.append({
                "object": "block",
                "type": "heading_1",
                "heading_1": {
                    "rich_text": [{"type": "text", "text": {"content": line_stripped[2:]}}],
                },
            })
        elif line_stripped.startswith("- ") or line_stripped.startswith("* "):  # Convert bullet points
            blocks.append({
                "object": "block",
                "type": "bulleted_list_item",
                "bulleted_list_item": {
                    "rich_text": [{"type": "text", "text": {"content": line_stripped[2:]}}],
                },
            })
        else:  # Convert paragraphs
            blocks.append({
                "object": "block",
                "type": "paragraph",
                "paragraph": {
                    "rich_text": [{"type": "text", "text": {"content": line_stripped}}],
                },
            })
    return blocks

def notes_to_notion(notion_api_token, notion_page_id, notes_or_blocks, title="Class Notes - AI Agent"):
    if not notion_api_token or not notion_page_id:
        print("[Notion] Skipped: NOTION_API_TOKEN or NOTION_PAGE_ID not set.")
        return False

    notion = Client(auth=notion_api_token)
    if isinstance(notes_or_blocks, list):
        blocks = notes_or_blocks
    else:
        blocks = format_notes_for_notion(notes_or_blocks)

    try:
        notion.pages.create(
            parent={"type": "page_id", "page_id": notion_page_id},
            properties={"title": [{"type": "text", "text": {"content": title}}]},
            children=blocks[:100],  # Notion limits children to 100 blocks per request
        )
        print("Notes successfully added to Notion!")
        return True
    except Exception as e:
        print(f"Error sending notes to Notion: {e}")
        return False
